const fs = require('fs');
const path = require('path');

const briefsDir = path.join(__dirname, '../briefs');
const reportsDir = path.join(__dirname, '../out/reports');
const checkpointPath = path.join(__dirname, '../checkpoint.json');

if (!fs.existsSync(reportsDir)) {
  fs.mkdirSync(reportsDir, { recursive: true });
}

const files = fs.readdirSync(briefsDir).filter(f => f.endsWith('.txt')).sort();

const STANDARD_PROJECT_HEADINGS = [
  'PROBLEM STATEMENT',
  'USE CASES IN THE REAL WORLD',
  'WHY THIS IS HARD (COMPETENCY REDUCER)',
  'RECRUITER SHORTLIST SIGNAL',
  'ARCHITECTURE & DATA FLOW',
  'SCALE & PERFORMANCE TARGETS',
  'SKILLS COVERED',
  'SCREENER VERIFICATION RUBRIC',
  'RESUME BULLET FORMULA',
];

const STANDARD_CERT_HEADINGS = [
  'OVERVIEW & VALUE PROPOSITION',
  'EXAM FORMAT & PREREQUISITES',
  'FEES & OFFICIAL PRICING',
  'STUDENT AID & FEE WAIVER',
  'SYLLABUS & CORE DOMAINS',
  'VALIDITY & RENEWAL POLICY',
  'VERIFICATION METHOD',
  'RESUME BULLET FORMULA',
];

const CERT_KEYWORDS = ['issuer', 'exam', 'fees', 'syllabus', 'validity', 'waiver'];

const inventory = [];
const checkpointEntries = [];

for (const file of files) {
  const filePath = path.join(briefsDir, file);
  const content = fs.readFileSync(filePath, 'utf8');
  const lines = content.split(/\r?\n/);
  const slug = path.basename(file, '.txt');

  // 1. Extract Title
  let title = slug;
  const firstLine = lines[0] || '';
  if (firstLine.includes('—')) {
    title = firstLine.split('—')[1].trim();
  } else if (firstLine.includes('-')) {
    title = firstLine.split('-')[1].trim();
  }

  // 2. Extract Headers from metadata block
  let domain = 'Unknown';
  let difficulty = 'UNKNOWN';
  let estimatedHours = 0;
  let techStack = [];
  let skills = [];

  for (let i = 0; i < Math.min(lines.length, 15); i++) {
    const line = lines[i];
    if (/^domain\s*:/i.test(line)) {
      domain = line.split(/:\s*/)[1]?.trim() || 'Unknown';
    } else if (/^difficulty\s*:/i.test(line)) {
      difficulty = line.split(/:\s*/)[1]?.trim().toUpperCase() || 'UNKNOWN';
    } else if (/^est\.\s*time\s*:/i.test(line)) {
      const match = line.match(/(\d+)/);
      if (match) estimatedHours = parseInt(match[1], 10);
    } else if (/^tech\s*stack\s*:/i.test(line)) {
      const raw = line.split(/:\s*/)[1]?.trim() || '';
      techStack = raw.split(',').map(s => s.trim()).filter(Boolean);
    } else if (/^skills\s*:/i.test(line)) {
      const raw = line.split(/:\s*/)[1]?.trim() || '';
      skills = raw.split(',').map(s => s.trim()).filter(Boolean);
    }
  }

  // 3. Extract Section Headings
  const headingsFound = [];
  const sectionContent = {};
  let currentSection = null;
  let currentSectionLines = [];

  for (let i = 0; i < lines.length; i++) {
    const line = lines[i].trim();
    const nextLine = (lines[i + 1] || '').trim();

    // Check if line is an uppercase section heading followed by a dashed line
    const isHeading =
      line.length > 2 &&
      line === line.toUpperCase() &&
      /^[A-Z0-9\s&(),—\-_:.]+$/.test(line) &&
      !line.startsWith('PROJECT BRIEF') &&
      !line.startsWith('CERTIFICATION PAGE') &&
      !line.startsWith('===') &&
      !line.startsWith('---') &&
      (nextLine.startsWith('---') || nextLine.startsWith('==='));

    if (isHeading) {
      if (currentSection) {
        sectionContent[currentSection] = currentSectionLines.join(' ').trim();
      }
      currentSection = line;
      currentSectionLines = [];
      headingsFound.push(line);
      i++; // skip dashed separator line
      continue;
    }

    if (currentSection) {
      if (!line.startsWith('Generated by HireFlow')) {
        currentSectionLines.push(line);
      }
    }
  }
  if (currentSection) {
    sectionContent[currentSection] = currentSectionLines.join(' ').trim();
  }

  // If skills list wasn't in top metadata, check SKILLS COVERED section
  if (skills.length === 0 && sectionContent['SKILLS COVERED']) {
    skills = sectionContent['SKILLS COVERED'].split(',').map(s => s.trim()).filter(Boolean);
  }

  // 4. Extract Rubric Item Count
  let rubricItemCount = 0;
  const rubricText = sectionContent['SCREENER VERIFICATION RUBRIC'] || sectionContent['SYLLABUS & CORE DOMAINS'] || '';
  if (rubricText) {
    const items = rubricText.split(/\d+\.\s+/).filter(Boolean);
    rubricItemCount = items.length;
  }

  // 5. Target Lines
  const targetLines = sectionContent['SCALE & PERFORMANCE TARGETS'] || sectionContent['EXAM FORMAT & PREREQUISITES'] || '';

  // 6. Resume Bullet Formula
  const resumeBullet = sectionContent['RESUME BULLET FORMULA'] || '';

  // 7. Classify Type by keyword rules
  const lowerContent = content.toLowerCase();
  const certKeywordMatches = CERT_KEYWORDS.filter(k => lowerContent.includes(k));
  let type = 'unknown';

  if (certKeywordMatches.length >= 5) {
    type = 'certification_page';
  } else if (
    lowerContent.includes('problem statement') &&
    (lowerContent.includes('architecture') || lowerContent.includes('tech stack') || lowerContent.includes('rubric'))
  ) {
    type = 'project_brief';
  }

  inventory.push({
    id: slug,
    type,
    title,
    domain,
    difficulty,
    estimatedHours,
    techStack,
    skills,
    rubricItemCount,
    targetLines: targetLines.replace(/\n+/g, ' ').slice(0, 150),
    resumeBullet: resumeBullet.replace(/\n+/g, ' ').replace(/"/g, '""'),
    sectionHeadings: headingsFound,
    totalChars: content.length,
    totalLines: lines.length,
    certKeywordCount: certKeywordMatches.length,
  });

  checkpointEntries.push({
    id: slug,
    type,
    status: 'pending',
    attempts: 0,
  });
}

// ── Write /out/reports/inventory.csv ──
function escapeCsv(val) {
  if (val === null || val === undefined) return '""';
  const str = String(val);
  if (str.includes(',') || str.includes('"') || str.includes('\n')) {
    return `"${str.replace(/"/g, '""')}"`;
  }
  return `"${str}"`;
}

const csvHeader = [
  'id',
  'type',
  'title',
  'domain',
  'difficulty',
  'estimated_hours',
  'tech_stack',
  'skills',
  'rubric_item_count',
  'target_lines',
  'resume_bullet',
  'section_headings',
  'total_chars',
  'total_lines',
].join(',');

const csvRows = inventory.map(row => [
  escapeCsv(row.id),
  escapeCsv(row.type),
  escapeCsv(row.title),
  escapeCsv(row.domain),
  escapeCsv(row.difficulty),
  escapeCsv(row.estimatedHours),
  escapeCsv(row.techStack.join('; ')),
  escapeCsv(row.skills.join('; ')),
  escapeCsv(row.rubricItemCount),
  escapeCsv(row.targetLines),
  escapeCsv(row.resumeBullet),
  escapeCsv(row.sectionHeadings.join('; ')),
  escapeCsv(row.totalChars),
  escapeCsv(row.totalLines),
].join(','));

fs.writeFileSync(path.join(reportsDir, 'inventory.csv'), [csvHeader, ...csvRows].join('\n'), 'utf8');

// ── Initialize /checkpoint.json ──
fs.writeFileSync(checkpointPath, JSON.stringify(checkpointEntries, null, 2), 'utf8');

// ── Compile Statistical Report ──

// 1. Counts by Type
const typeCounts = {};
for (const item of inventory) {
  typeCounts[item.type] = (typeCounts[item.type] || 0) + 1;
}

// 2. Counts by Domain
const domainCounts = {};
for (const item of inventory) {
  domainCounts[item.domain] = (domainCounts[item.domain] || 0) + 1;
}

// 3. Heading Variations & Missing Headings
const filesMissingStandardHeadings = [];
const allDistinctHeadings = new Set();

for (const item of inventory) {
  const headings = new Set(item.sectionHeadings);
  item.sectionHeadings.forEach(h => allDistinctHeadings.add(h));

  const standard = item.type === 'certification_page' ? STANDARD_CERT_HEADINGS : STANDARD_PROJECT_HEADINGS;
  const missing = standard.filter(h => !headings.has(h));

  if (missing.length > 0) {
    filesMissingStandardHeadings.push({
      id: item.id,
      type: item.type,
      missing,
    });
  }
}

// 4. Duplicate or Near-Duplicate Projects (same domain & >70% tech-stack overlap)
function jaccardSimilarity(arr1, arr2) {
  const set1 = new Set(arr1.map(s => s.toLowerCase().trim()));
  const set2 = new Set(arr2.map(s => s.toLowerCase().trim()));
  if (set1.size === 0 && set2.size === 0) return 1.0;
  if (set1.size === 0 || set2.size === 0) return 0.0;
  let intersection = 0;
  for (const item of set1) {
    if (set2.has(item)) intersection++;
  }
  const union = new Set([...set1, ...set2]).size;
  return intersection / union;
}

const nearDuplicates = [];
for (let i = 0; i < inventory.length; i++) {
  for (let j = i + 1; j < inventory.length; j++) {
    const a = inventory[i];
    const b = inventory[j];
    if (a.domain.toLowerCase() === b.domain.toLowerCase()) {
      const overlap = jaccardSimilarity(a.techStack, b.techStack);
      if (overlap >= 0.70) {
        nearDuplicates.push({
          projectA: a.id,
          projectB: b.id,
          domain: a.domain,
          overlapPercentage: Math.round(overlap * 100),
          commonStack: a.techStack.filter(t => b.techStack.map(x => x.toLowerCase()).includes(t.toLowerCase())),
        });
      }
    }
  }
}

// 5. Difficulty vs Hours Distribution
const diffDistribution = {};
for (const item of inventory) {
  const d = item.difficulty;
  if (!diffDistribution[d]) {
    diffDistribution[d] = { count: 0, totalHours: 0, minHours: Infinity, maxHours: -Infinity, hoursList: [] };
  }
  diffDistribution[d].count++;
  diffDistribution[d].totalHours += item.estimatedHours;
  diffDistribution[d].minHours = Math.min(diffDistribution[d].minHours, item.estimatedHours);
  diffDistribution[d].maxHours = Math.max(diffDistribution[d].maxHours, item.estimatedHours);
  diffDistribution[d].hoursList.push(item.estimatedHours);
}

for (const d of Object.keys(diffDistribution)) {
  const stats = diffDistribution[d];
  stats.avgHours = Math.round((stats.totalHours / stats.count) * 10) / 10;
  stats.hoursList.sort((a, b) => a - b);
  const mid = Math.floor(stats.hoursList.length / 2);
  stats.medianHours = stats.hoursList.length % 2 !== 0
    ? stats.hoursList[mid]
    : (stats.hoursList[mid - 1] + stats.hoursList[mid]) / 2;
  delete stats.hoursList;
}

const reportSummary = {
  totalBriefsScanned: inventory.length,
  countsByType: typeCounts,
  countsByDomain: domainCounts,
  missingHeadingsCount: filesMissingStandardHeadings.length,
  missingHeadingsDetails: filesMissingStandardHeadings,
  allDistinctHeadingsFound: Array.from(allDistinctHeadings),
  nearDuplicatesCount: nearDuplicates.length,
  nearDuplicates,
  difficultyVsHours: diffDistribution,
};

fs.writeFileSync(
  path.join(reportsDir, 'inventory_summary.json'),
  JSON.stringify(reportSummary, null, 2),
  'utf8'
);

