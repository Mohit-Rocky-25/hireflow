const fs = require('fs');
const path = require('path');

// 1. Export 78 Project Build Briefs
const projectBriefs = JSON.parse(
  fs.readFileSync(path.join(__dirname, '../src/data/suite/project-briefs.json'), 'utf8')
);

function buildProjectBriefText(brief) {
  return [
    `PROJECT BRIEF — ${brief.title}`,
    `======================================================================`,
    ``,
    `Domain    : ${brief.domain}`,
    `Difficulty: ${String(brief.difficulty).toUpperCase()}`,
    `Est. Time : ${brief.estimatedHours} hours`,
    `Tech Stack: ${(brief.techStack || []).join(', ')}`,
    ``,
    `PROBLEM STATEMENT`,
    `----------------------------------------`,
    brief.problemStatement || '—',
    ``,
    `USE CASES IN THE REAL WORLD`,
    `----------------------------------------`,
    brief.useCases || '—',
    ``,
    `WHY THIS IS HARD (COMPETENCY REDUCER)`,
    `----------------------------------------`,
    brief.problemItSolves || '—',
    ``,
    `RECRUITER SHORTLIST SIGNAL`,
    `----------------------------------------`,
    brief.recruiterSignal || '—',
    ``,
    `ARCHITECTURE & DATA FLOW`,
    `----------------------------------------`,
    brief.architecture || '—',
    ``,
    `SCALE & PERFORMANCE TARGETS`,
    `----------------------------------------`,
    brief.scaleTargets || '—',
    ``,
    `SKILLS COVERED`,
    `----------------------------------------`,
    (brief.coveredSkills || []).join(', '),
    ``,
    `SCREENER VERIFICATION RUBRIC`,
    `----------------------------------------`,
    (brief.verificationRubric || []).map((r, i) => `${i + 1}. ${r}`).join('\n'),
    ``,
    `RESUME BULLET FORMULA`,
    `----------------------------------------`,
    `"${brief.portfolioBulletFormula || ''}"`,
    ``,
    `Generated by HireFlow — hireflow.io`,
    ``,
  ].join('\n');
}

const briefsDir = path.join(__dirname, '../briefs');
if (!fs.existsSync(briefsDir)) {
  fs.mkdirSync(briefsDir, { recursive: true });
}

let projectCount = 0;
for (const brief of projectBriefs) {
  const filename = `${brief.id}.txt`;
  fs.writeFileSync(path.join(briefsDir, filename), buildProjectBriefText(brief), 'utf8');
  projectCount++;
}

console.log(`Successfully exported ${projectCount} project briefs to /briefs`);
