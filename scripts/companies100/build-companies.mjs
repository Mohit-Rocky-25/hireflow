import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const REPO_ROOT = path.resolve(__dirname, '../..');

export function computeSha256(content) {
  return crypto.createHash('sha256').update(content, 'utf8').digest('hex');
}

export function formatGeneratedHeader(contentBody) {
  const hash = computeSha256(contentBody);
  return `// @generated hireflow:companies-100 hash:sha256:${hash}\n// DO NOT EDIT MANUALLY. Generated by scripts/companies100/build-companies.mjs from ledger.\n\n${contentBody}`;
}

export function generateCompaniesArtifacts(options = {}) {
  const {
    rosterPath = path.join(REPO_ROOT, 'docs/companies-100/roster-parsed.json'),
    ledgerDir = path.join(REPO_ROOT, 'docs/companies-100/ledger'),
    templatesPath = path.join(REPO_ROOT, 'src/data/market/companies100/templates/job-families.json')
  } = options;

  if (!fs.existsSync(rosterPath)) {
    throw new Error(`Roster file not found: ${rosterPath}`);
  }

  const rosterRaw = JSON.parse(fs.readFileSync(rosterPath, 'utf8'));
  const roster = rosterRaw.categories
    ? rosterRaw.categories.flatMap(cat => cat.companies)
    : (rosterRaw.companies || (Array.isArray(rosterRaw) ? rosterRaw : []));
  const templates = fs.existsSync(templatesPath) ? JSON.parse(fs.readFileSync(templatesPath, 'utf8')) : {};

  const ledgerFiles = fs.existsSync(ledgerDir) ? fs.readdirSync(ledgerDir).filter(f => f.endsWith('.json')) : [];
  const ledgerMap = new Map();

  for (const file of ledgerFiles) {
    const companyId = path.basename(file, '.json');
    const content = JSON.parse(fs.readFileSync(path.join(ledgerDir, file), 'utf8'));
    const rows = Array.isArray(content) ? content : (content.rows || []);
    if (rows.length > 0) {
      ledgerMap.set(companyId, rows);
    }
  }

  const generatedCompanies = [];
  const generatedEligibility = {};

  let totalLedgerRowsProcessed = 0;

  for (const item of roster) {
    const id = item.id;
    const rows = ledgerMap.get(id);

    // Rule H1: Only include companies with verified ledger rows
    if (!rows || rows.length === 0) {
      continue;
    }

    totalLedgerRowsProcessed += rows.length;

    // Aggregate ledger values
    const ledgerValues = {};
    const jobFamilies = [];

    for (const r of rows) {
      if (r.field === 'jobFamily') {
        if (r.value && !jobFamilies.includes(r.value)) {
          jobFamilies.push(r.value);
        }
      } else {
        ledgerValues[r.field] = r.value;
      }
    }

    const companyName = ledgerValues['officialName'] || item.name;
    const hq = ledgerValues['hq'] || null;
    const officialSiteUrl = ledgerValues['officialSiteUrl'] || null;
    const careersUrl = ledgerValues['careersUrl'] || null;
    const campusPageUrl = ledgerValues['campusPageUrl'] || null;
    const industry = ledgerValues['industry'] || item.sector;

    const ledgerContent = JSON.parse(fs.readFileSync(path.join(ledgerDir, `${id}.json`), 'utf8'));
    const depth = ledgerContent.depth || (jobFamilies.length >= 2 && ledgerValues['eligibility.aggregatePercent'] ? 'deep' : (jobFamilies.length > 0 ? 'standard' : 'basic'));

    // Build role list from verified job families and templates (basic has none)
    const roles = [];
    if (depth !== 'basic') {
      const maxRoles = depth === 'deep' ? 5 : 2;
      const familiesToBuild = (jobFamilies.length > 0 ? jobFamilies : ['software-engineer']).slice(0, maxRoles);

      for (const famKey of familiesToBuild) {
        const tmpl = templates[famKey] || templates['software-engineer'];
        if (!tmpl) continue;

        const roleId = `${id}-${famKey}`;
        const overview = tmpl.overviewTemplate ? tmpl.overviewTemplate.replace(/\{\{companyName\}\}/g, companyName) : '';
        const fullText = [
          `Representative role profile (editorial). Not an actual job posting. See the official careers page: ${careersUrl || officialSiteUrl || 'https://hireflow.internal'}`,
          `Company: ${companyName}`,
          `Role: ${tmpl.title}`,
          `Level: ${tmpl.level}`,
          `Overview: ${overview}`,
          `Responsibilities:\n- ` + tmpl.keyResponsibilities.join('\n- '),
          `Requirements:\n- ` + tmpl.requiredSkills.join('\n- ')
        ].join('\n\n');

        roles.push({
          id: roleId,
          companyId: id,
          title: tmpl.title,
          level: tmpl.level,
          track: tmpl.track,
          overview,
          responsibilities: tmpl.keyResponsibilities,
          requirements: tmpl.requiredSkills,
          fullText,
          profileKind: 'representative',
          jobFamily: famKey
        });
      }
    }

    const companyObj = {
      id,
      name: companyName,
      logo: item.logo || companyName.split(' ').map(w => w[0]).join('').slice(0, 3).toUpperCase(),
      gradient: item.gradient || 'from-blue-600 to-indigo-600',
      sector: industry,
      industry,
      tier: item.tier || 'Enterprise',
      hq,
      depth,
      dataStatus: 'sourced',
      officialSiteUrl,
      careersUrl,
      campusPageUrl,
      tierRationale: ledgerContent.tierRationale || item.tierRationale || '',
      editorial: false,
      roles
    };

    generatedCompanies.push(companyObj);

    // Build eligibility object
    const aggPct = ledgerValues['eligibility.aggregatePercent'];
    const cgpa = ledgerValues['eligibility.cgpa'];
    const backlog = ledgerValues['eligibility.backlogRule'];
    const branches = ledgerValues['eligibility.branches'];
    const batchYears = ledgerValues['eligibility.batchYears'];

    if (aggPct !== undefined || cgpa !== undefined || backlog !== undefined || branches !== undefined || batchYears !== undefined) {
      generatedEligibility[id] = {
        companyId: id,
        minAggregatePercent: aggPct !== undefined ? aggPct : null,
        minCgpa: cgpa !== undefined ? cgpa : null,
        backlogRule: backlog !== undefined ? backlog : null,
        eligibleBranches: branches !== undefined ? branches : null,
        eligibleBatchYears: batchYears !== undefined ? batchYears : null
      };
    }
  }

  // Generate companies.ts body
  const companiesBody = `export interface CompanyRole {
  id: string;
  companyId: string;
  title: string;
  level: string;
  track: string;
  overview: string;
  responsibilities: string[];
  requirements: string[];
  fullText: string;
  profileKind?: 'representative';
  jobFamily?: string;
  competencies?: string[];
  reqLevel?: Record<string, string>;
  uncoveredSkills?: string[];
  competencyFit?: 'good' | 'approximate';
}

export interface CompanyRecord {
  id: string;
  name: string;
  logo?: string;
  gradient?: string;
  sector: string;
  industry?: string;
  tier: string;
  hq: string | null;
  depth?: 'deep' | 'standard' | 'basic';
  dataStatus?: 'legacy_unaudited' | 'sourced' | 'editorial' | 'quarantined';
  officialSiteUrl: string | null;
  careersUrl: string | null;
  campusPageUrl: string | null;
  tierRationale?: string;
  editorial?: boolean;
  roles: CompanyRole[];
}

export const companies100: CompanyRecord[] = ${JSON.stringify(generatedCompanies, null, 2)};
`;

  // Generate eligibility.ts body
  const eligibilityBody = `export interface CompanyEligibilityRule {
  companyId: string;
  minAggregatePercent: number | null;
  minCgpa: number | null;
  backlogRule: string | null;
  eligibleBranches: string[] | null;
  eligibleBatchYears: number[] | null;
  companyName?: string;
  displayName?: string;
  aggregatePercent?: number | null;
  cgpaEquivalent?: number | null;
  sourceName?: string;
  sourceUrl?: string;
  sourceKind?: 'official' | 'company-published';
  notes?: string;
  confidence?: 'high' | 'medium';
  lastReviewed?: string;
}

export const companies100Eligibility: Record<string, CompanyEligibilityRule> = ${JSON.stringify(generatedEligibility, null, 2)};
`;

  const finalCompaniesContent = formatGeneratedHeader(companiesBody);
  const finalEligibilityContent = formatGeneratedHeader(eligibilityBody);

  const manifest = {
    generatedAt: new Date().toISOString(),
    totalCompaniesCount: generatedCompanies.length,
    totalEligibilityRulesCount: Object.keys(generatedEligibility).length,
    totalLedgerRowsProcessed,
    hashes: {
      companiesTs: computeSha256(companiesBody),
      eligibilityTs: computeSha256(eligibilityBody)
    }
  };

  return {
    finalCompaniesContent,
    finalEligibilityContent,
    manifest,
    companiesBody,
    eligibilityBody
  };
}

export function buildCompaniesArtifacts() {
  const generatedDir = path.join(REPO_ROOT, 'src/data/market/companies100/generated');
  fs.mkdirSync(generatedDir, { recursive: true });

  const artifacts = generateCompaniesArtifacts();

  const companiesPath = path.join(generatedDir, 'companies.ts');
  const eligibilityPath = path.join(generatedDir, 'eligibility.ts');
  const manifestPath = path.join(generatedDir, 'manifest.json');

  fs.writeFileSync(companiesPath, artifacts.finalCompaniesContent, 'utf8');
  fs.writeFileSync(eligibilityPath, artifacts.finalEligibilityContent, 'utf8');
  fs.writeFileSync(manifestPath, JSON.stringify(artifacts.manifest, null, 2), 'utf8');

  return {
    ...artifacts,
    paths: {
      companiesPath,
      eligibilityPath,
      manifestPath
    }
  };
}

// CLI runner
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  console.log('=== HireFlow Companies-100 Code Generator (Rule H1) ===');
  const artifacts = buildCompaniesArtifacts();
  console.log(`✅ Generated artifacts:`);
  console.log(`  - ${artifacts.paths.companiesPath} (${artifacts.manifest.totalCompaniesCount} companies)`);
  console.log(`  - ${artifacts.paths.eligibilityPath} (${artifacts.manifest.totalEligibilityRulesCount} eligibility rules)`);
  console.log(`  - ${artifacts.paths.manifestPath} (Processed ${artifacts.manifest.totalLedgerRowsProcessed} ledger rows)`);
}

