/**
 * Resolves a verified working careers portal URL for any given company ID or name.
 */
export function getVerifiedCompanyUrl(companyIdOrName?: string): string | undefined {
  if (!companyIdOrName) return undefined;
  const raw = companyIdOrName.toLowerCase().trim();
  const cleaned = raw.replace(/[^a-z0-9]/g, '');

  if (VERIFIED_COMPANY_URLS[raw]) return VERIFIED_COMPANY_URLS[raw];
  if (VERIFIED_COMPANY_URLS[cleaned]) return VERIFIED_COMPANY_URLS[cleaned];

  for (const [key, url] of Object.entries(VERIFIED_COMPANY_URLS)) {
    if (cleaned.length >= 3 && (cleaned.includes(key) || key.includes(cleaned))) {
      return url;
    }
  }
  return undefined;
}

