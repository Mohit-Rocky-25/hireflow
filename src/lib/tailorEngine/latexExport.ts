import { ResumeDocModel } from './docModel';

/**
 * Escapes special LaTeX characters in plain text strings.
 */
export function escapeLatex(text: string): string {
  if (!text) return '';
  return text
    .replace(/\\/g, '\\textbackslash{}')
    .replace(/[{}]/g, (m) => `\\${m}`)
    .replace(/[$&#%_]/g, (m) => `\\${m}`)
    .replace(/\^/g, '\\textasciicircum{}')
    .replace(/~/g, '\\textasciitilde{}')
    .replace(/[-•*●▪‣]\s*/g, ''); // strip bullet prefix
}

/**
 * Generates compile-ready LaTeX code in standard Jake's Resume format.
 */
export function generateLatexCode(model: ResumeDocModel): string {
  const name = escapeLatex(model.contact.name || 'Candidate Name');
  
  const contactItems: string[] = [];
  if (model.contact.email) {
    contactItems.push(`\\href{mailto:${model.contact.email}}{${escapeLatex(model.contact.email)}}`);
  }
  if (model.contact.phone) {
    contactItems.push(escapeLatex(model.contact.phone));
  }
  if (model.contact.location) {
    contactItems.push(escapeLatex(model.contact.location));
  }
  if (model.contact.links && model.contact.links.length > 0) {
    model.contact.links.forEach((link) => {
      const clean = link.replace(/^https?:\/\//i, '');
      contactItems.push(`\\href{https://${clean}}{${escapeLatex(clean)}}`);
    });
  }

  const lines: string[] = [];

  // Preamble
  lines.push(`%-------------------------`);
  lines.push(`% Resume in LaTeX (Jake's Resume Format)`);
  lines.push(`% Generated by HireFlow Tailor Engine`);
  lines.push(`%-------------------------`);
  lines.push(``);
  lines.push(`\\documentclass[letterpaper,10pt]{article}`);
  lines.push(``);
  lines.push(`\\usepackage{latexsym}`);
  lines.push(`\\usepackage[empty]{fullpage}`);
  lines.push(`\\usepackage{titlesec}`);
  lines.push(`\\usepackage{marvosym}`);
  lines.push(`\\usepackage[usenames,dvipsnames]{color}`);
  lines.push(`\\usepackage{verbatim}`);
  lines.push(`\\usepackage{enumitem}`);
  lines.push(`\\usepackage[hidelinks]{hyperref}`);
  lines.push(`\\usepackage{fancyhdr}`);
  lines.push(`\\usepackage[english]{babel}`);
  lines.push(`\\usepackage{tabularx}`);
  lines.push(``);
  lines.push(`\\pagestyle{fancy}`);
  lines.push(`\\fancyhf{}`);
  lines.push(`\\renewcommand{\\headrulewidth}{0pt}`);
  lines.push(`\\renewcommand{\\footrulewidth}{0pt}`);
  lines.push(``);
  lines.push(`% Adjust margins`);
  lines.push(`\\addtolength{\\oddsidemargin}{-0.5in}`);
  lines.push(`\\addtolength{\\evensidemargin}{-0.5in}`);
  lines.push(`\\addtolength{\\textwidth}{1in}`);
  lines.push(`\\addtolength{\\topmargin}{-.5in}`);
  lines.push(`\\addtolength{\\textheight}{1.0in}`);
  lines.push(``);
  lines.push(`\\urlstyle{same}`);
  lines.push(`\\raggedbottom`);
  lines.push(`\\raggedright`);
  lines.push(`\\setlength{\\tabcolsep}{0in}`);
  lines.push(``);
  lines.push(`% Sections formatting`);
  lines.push(`\\titleformat{\\section}{`);
  lines.push(`  \\vspace{-4pt}\\scshape\\raggedright\\large`);
  lines.push(`}{}{0em}{}[\\color{black}\\titlerule \\vspace{-5pt}]`);
  lines.push(``);
  lines.push(`\\newcommand{\\resumeItem}[1]{`);
  lines.push(`  \\item\\small{`);
  lines.push(`    {#1 \\vspace{-2pt}}`);
  lines.push(`  }`);
  lines.push(`}`);
  lines.push(``);
  lines.push(`\\newcommand{\\resumeSubheading}[4]{`);
  lines.push(`  \\vspace{-2pt}\\item`);
  lines.push(`    \\begin{tabular*}{0.97\\textwidth}[t]{l@{\\extracolsep{\\fill}}r}`);
  lines.push(`      \\textbf{#1} & #2 \\\\`);
  lines.push(`      \\textit{\\small#3} & \\textit{\\small #4} \\\\`);
  lines.push(`    \\end{tabular*}\\vspace{-7pt}`);
  lines.push(`}`);
  lines.push(``);
  lines.push(`\\newcommand{\\resumeProjectHeading}[2]{`);
  lines.push(`    \\item`);
  lines.push(`    \\begin{tabular*}{0.97\\textwidth}{l@{\\extracolsep{\\fill}}r}`);
  lines.push(`      \\small#1 & #2 \\\\`);
  lines.push(`    \\end{tabular*}\\vspace{-7pt}`);
  lines.push(`}`);
  lines.push(``);
  lines.push(`\\newcommand{\\resumeSubHeadingListStart}{\\begin{itemize}[leftmargin=0.15in, label={}]}`);
  lines.push(`\\newcommand{\\resumeSubHeadingListEnd}{\\end{itemize}}`);
  lines.push(`\\newcommand{\\resumeItemListStart}{\\begin{itemize}[leftmargin=0.15in]}`);
  lines.push(`\\newcommand{\\resumeItemListEnd}{\\end{itemize}\\vspace{-5pt}}`);
  lines.push(``);
  lines.push(`\\begin{document}`);
  lines.push(``);

  // Heading
  lines.push(`%----------HEADING----------`);
  lines.push(`\\begin{center}`);
  lines.push(`    \\textbf{\\Huge \\scshape ${name}} \\\\[4pt]`);
  if (contactItems.length > 0) {
    lines.push(`    \\small ${contactItems.join(' $|$ ')}`);
  }
  lines.push(`\\end{center}`);
  lines.push(``);

  // Summary
  if (model.summary) {
    lines.push(`%-----------SUMMARY-----------`);
    lines.push(`\\section{Professional Summary}`);
    lines.push(`\\small{${escapeLatex(model.summary)}}`);
    lines.push(`\\vspace{2pt}`);
    lines.push(``);
  }

  // Education
  if (model.education && model.education.length > 0) {
    lines.push(`%-----------EDUCATION-----------`);
    lines.push(`\\section{Education}`);
    lines.push(`\\resumeSubHeadingListStart`);
    model.education.forEach((edu) => {
      const degree = escapeLatex(edu.degree || 'Degree');
      const inst = escapeLatex(edu.institution || '');
      const year = escapeLatex(edu.year || '');
      const details = escapeLatex(edu.details || '');
      lines.push(`    \\resumeSubheading`);
      lines.push(`      {${inst}}{${year}}`);
      lines.push(`      {${degree}${details ? ` -- ${details}` : ''}}{}`);
    });
    lines.push(`\\resumeSubHeadingListEnd`);
    lines.push(``);
  }

  // Technical Skills
  if (model.skills && model.skills.length > 0) {
    lines.push(`%-----------TECHNICAL SKILLS-----------`);
    lines.push(`\\section{Technical Skills}`);
    lines.push(`\\begin{itemize}[leftmargin=0.15in, label={}]`);
    lines.push(`    \\small{\\item{`);

    if (model.skillCategories && model.skillCategories.length > 0) {
      const skillGroups = model.skillCategories.map((g) => {
        const catName = escapeLatex(g.category);
        const skillList = g.skills.map((s) => escapeLatex(s)).join(', ');
        return `     \\textbf{${catName}:} {${skillList}} \\\\[2pt]`;
      });
      lines.push(skillGroups.join('\n'));
    } else {
      const allSkills = model.skills.map((s) => escapeLatex(s)).join(', ');
      lines.push(`     \\textbf{Skills:} {${allSkills}}`);
    }

    lines.push(`    }}`);
    lines.push(`\\end{itemize}`);
    lines.push(``);
  }

  // Projects
  if (model.projects && model.projects.length > 0) {
    lines.push(`%-----------PROJECTS-----------`);
    lines.push(`\\section{Projects}`);
    lines.push(`\\resumeSubHeadingListStart`);
    model.projects.forEach((proj) => {
      const pName = escapeLatex(proj.name);
      const pDate = escapeLatex(proj.date || '');
      const pTools = proj.linkOrTech ? ` $|$ \\emph{Tools: ${escapeLatex(proj.linkOrTech)}}` : '';

      lines.push(`    \\resumeProjectHeading`);
      lines.push(`      {\\textbf{${pName}}${pTools}}{${pDate}}`);

      if (proj.bullets && proj.bullets.length > 0) {
        lines.push(`      \\resumeItemListStart`);
        proj.bullets.forEach((b) => {
          lines.push(`        \\resumeItem{${escapeLatex(b.text)}}`);
        });
        lines.push(`      \\resumeItemListEnd`);
      }
    });
    lines.push(`\\resumeSubHeadingListEnd`);
    lines.push(``);
  }

  // Work Experience
  if (model.experience && model.experience.length > 0) {
    lines.push(`%-----------EXPERIENCE-----------`);
    lines.push(`\\section{Experience}`);
    lines.push(`\\resumeSubHeadingListStart`);
    model.experience.forEach((exp) => {
      const role = escapeLatex(exp.role || '');
      const comp = escapeLatex(exp.company || '');
      const dates = escapeLatex(exp.dates || '');
      const loc = escapeLatex(exp.location || '');

      lines.push(`    \\resumeSubheading`);
      lines.push(`      {${role}}{${dates}}`);
      lines.push(`      {${comp}}{${loc}}`);

      if (exp.bullets && exp.bullets.length > 0) {
        lines.push(`      \\resumeItemListStart`);
        exp.bullets.forEach((b) => {
          lines.push(`        \\resumeItem{${escapeLatex(b.text)}}`);
        });
        lines.push(`      \\resumeItemListEnd`);
      }
    });
    lines.push(`\\resumeSubHeadingListEnd`);
    lines.push(``);
  }

  // Achievements
  if (model.achievements && model.achievements.length > 0) {
    lines.push(`%-----------ACHIEVEMENTS-----------`);
    lines.push(`\\section{Achievements}`);
    lines.push(`\\resumeItemListStart`);
    model.achievements.forEach((ach) => {
      lines.push(`    \\resumeItem{${escapeLatex(ach)}}`);
    });
    lines.push(`\\resumeItemListEnd`);
    lines.push(``);
  }

  // Certifications
  if (model.certifications && model.certifications.length > 0) {
    lines.push(`%-----------CERTIFICATIONS-----------`);
    lines.push(`\\section{Certifications}`);
    lines.push(`\\resumeItemListStart`);
    model.certifications.forEach((cert) => {
      lines.push(`    \\resumeItem{${escapeLatex(cert)}}`);
    });
    lines.push(`\\resumeItemListEnd`);
    lines.push(``);
  }

  lines.push(`\\end{document}`);

  return lines.join('\n');
}

/**
 * Creates a downloadable Blob containing the LaTeX source file.
 */
export function generateLatexBlob(model: ResumeDocModel): Blob {
  const code = generateLatexCode(model);
  return new Blob([code], { type: 'text/x-tex;charset=utf-8' });
}
