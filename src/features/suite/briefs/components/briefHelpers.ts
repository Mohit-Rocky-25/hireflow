export function buildBriefText(brief: ProjectBrief): string {
  return [
    `PROJECT BRIEF — ${brief.title}`,
    `${'='.repeat(70)}`,
    ``,
    `Domain    : ${brief.domain}`,
    `Difficulty: ${brief.difficulty.toUpperCase()}`,
    `Est. Time : ${brief.estimatedHours} hours`,
    `Tech Stack: ${brief.techStack.join(', ')}`,
    ``,
    `PROBLEM STATEMENT`,
    `-`.repeat(40),
    brief.problemStatement,
    ``,
    `USE CASES IN THE REAL WORLD`,
    `-`.repeat(40),
    brief.useCases || '—',
    ``,
    `WHY THIS IS HARD (COMPETENCY REDUCER)`,
    `-`.repeat(40),
    brief.problemItSolves || '—',
    ``,
    `WHAT THIS PROJECT DEMONSTRATES`,
    `-`.repeat(40),
    brief.recruiterSignal || '—',
    ``,
    `ARCHITECTURE & DATA FLOW`,
    `-`.repeat(40),
    brief.architecture,
    ``,
    `SCALE & PERFORMANCE TARGETS`,
    `-`.repeat(40),
    brief.scaleTargets,
    ``,
    `SKILLS COVERED`,
    `-`.repeat(40),
    brief.coveredSkills.join(', '),
    ``,
    `SCREENER VERIFICATION RUBRIC`,
    `-`.repeat(40),
    brief.verificationRubric.map((r, i) => `${i + 1}. ${r}`).join('\n'),
    ``,
    `RESUME BULLET FORMULA`,
    `-`.repeat(40),
    `"${brief.portfolioBulletFormula}"`,
    ``,
    `Generated by HireFlow — hireflow.io`,
  ].join('\n');
}
