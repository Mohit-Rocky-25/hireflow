/**
 * HireFlow v4: Project Scaffold Generator (D17)
 * Generates client-side production-ready starter scaffolds (.zip) using JSZip.
 * Includes README with Architecture Mermaid diagram, package config, .gitignore,
 * starter source boilerplate, and failing acceptance tests.
 */

import JSZip from 'jszip';
import { ProjectBrief } from './bundleBriefs';
import { safeSlug } from '../../../lib/safeUtils';

export async function generateProjectScaffoldZip(brief: ProjectBrief): Promise<{ filename: string; blob: Blob }> {
  const zip = new JSZip();
  const slug = safeSlug(brief.title);
  const isPython = brief.techStack.some((t) => /python|fastapi|django|flask|pytorch/i.test(t));
  const isGo = brief.techStack.some((t) => /golang|go/i.test(t));

  // 1. README.md with Mermaid Architecture Diagram
  const readmeContent = `# ${brief.title}

> **Domain:** ${brief.domain} | **Difficulty:** ${brief.difficulty.toUpperCase()} | **Estimated Time:** ${brief.estimatedHours} hours
> **Target Tech Stack:** ${brief.techStack.join(', ')}

---

## 1. Problem Statement
${brief.problemStatement}

### Real-World Use Cases
${brief.useCases || 'Enterprise real-time data processing, high-scale service architecture.'}

### Recruiter Signals
${brief.recruiterSignal || 'Proves production engineering ownership, concurrency control, and clean system boundaries.'}

---

## 2. System Architecture

\`\`\`mermaid
graph TD
    Client[Client / Ingestion Layer] -->|HTTP / gRPC| API[API Gateway & Router]
    API -->|Process / Validate| Core[Core Business Engine]
    Core -->|Cache / Queue| Cache[(Redis / Kafka)]
    Core -->|Persist| DB[(Primary Database)]
\`\`\`

---

## 3. Core Acceptance Criteria & Milestones
${(brief.verificationRubric || ['Core architectural pipeline', 'Concurrency safety', 'Automated test suite'])
  .map((d: string, i: number) => `${i + 1}. **${d}**`)
  .join('\n')}

---

## 4. Getting Started

${
  isPython
    ? `\`\`\`bash
# Create virtual environment
python -m venv venv
source venv/bin/activate  # On Windows: venv\\Scripts\\activate

# Install dependencies
pip install -r requirements.txt

# Run acceptance tests
pytest
\`\`\``
    : `\`\`\`bash
# Install dependencies
npm install

# Run tests (starts with failing acceptance criteria)
npm test

# Start dev server
npm run dev
\`\`\``
}

---
*Generated by HireFlo v4 Build Briefs Toolkit — Client-Side Career Toolkit for Indian Engineering Freshers.*
`;

  zip.file('README.md', readmeContent);

  // 2. .gitignore
  const gitignoreContent = `# Dependencies
node_modules/
venv/
__pycache__/
*.pyc

# Build outputs
dist/
build/
*.egg-info/

# Logs & Environment
*.log
.env
.env.local
.DS_Store
Thumbs.db
`;
  zip.file('.gitignore', gitignoreContent);

  // 3. Dependency Configuration
  if (isPython) {
    const requirementsTxt = `# Core Dependencies for ${brief.title}
pytest>=8.0.0
pytest-asyncio>=0.23.0
pydantic>=2.6.0
`;
    zip.file('requirements.txt', requirementsTxt);

    // Python source
    const pySrc = `"""
${brief.title} - Core Engine
Generated by HireFlo Build Briefs
"""

class Engine:
    def __init__(self):
        # TODO: Initialize database connection and buffer queues
        pass

    def process(self, payload: dict) -> dict:
        """
        Processes inbound payload per specification.
        TODO: Implement core business logic and concurrency validation.
        """
        raise NotImplementedError("Implement processing pipeline")
`;
    zip.file('src/main.py', pySrc);

    // Python tests
    const pyTest = `"""
Acceptance Criteria Tests for ${brief.title}
"""
import pytest
from src.main import Engine

def test_engine_initialization():
    engine = Engine()
    assert engine is not None

def test_acceptance_criteria_pipeline():
    engine = Engine()
    # TODO: Implement test verifying primary acceptance criteria
    with pytest.raises(NotImplementedError):
        engine.process({"test": True})
`;
    zip.file('tests/test_main.py', pyTest);
  } else {
    // Node / TypeScript default
    const packageJson = {
      name: slug,
      version: '1.0.0',
      description: brief.title,
      main: 'dist/index.js',
      scripts: {
        build: 'tsc',
        dev: 'tsx watch src/index.ts',
        test: 'vitest run',
      },
      dependencies: {},
      devDependencies: {
        typescript: '^5.4.0',
        vitest: '^1.4.0',
        tsx: '^4.7.0',
      },
    };
    zip.file('package.json', JSON.stringify(packageJson, null, 2));

    const tsConfig = {
      compilerOptions: {
        target: 'ES2022',
        module: 'NodeNext',
        moduleResolution: 'NodeNext',
        strict: true,
        esModuleInterop: true,
        skipLibCheck: true,
        outDir: './dist',
      },
      include: ['src/**/*', 'tests/**/*'],
    };
    zip.file('tsconfig.json', JSON.stringify(tsConfig, null, 2));

    // TypeScript source
    const tsSrc = `/**
 * ${brief.title}
 * Generated by HireFlo Build Briefs
 */

export interface ProcessResult {
  success: boolean;
  timestamp: string;
}

export class CoreService {
  constructor() {
    // TODO: Initialize required caches, queues, and database connections
  }

  public async execute(input: Record<string, unknown>): Promise<ProcessResult> {
    // TODO: Implement primary algorithm and latency benchmarks
    throw new Error('Not implemented: Complete core engineering pipeline');
  }
}
`;
    zip.file('src/index.ts', tsSrc);

    // TypeScript tests
    const tsTest = `import { describe, it, expect } from 'vitest';
import { CoreService } from '../src/index';

describe('${brief.title} Acceptance Tests', () => {
  it('instantiates the core service', () => {
    const service = new CoreService();
    expect(service).toBeDefined();
  });

  it('fulfills core acceptance criteria', async () => {
    const service = new CoreService();
    // This starts as failing to guide the candidate step-by-step
    await expect(service.execute({ test: true })).rejects.toThrow('Not implemented');
  });
});
`;
    zip.file('tests/index.test.ts', tsTest);
  }

  const blob = await zip.generateAsync({ type: 'blob' });
  const filename = `${slug}-scaffold.zip`;
  return { filename, blob };
}

export function triggerDownloadBlob(blob: Blob, filename: string): void {
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}
